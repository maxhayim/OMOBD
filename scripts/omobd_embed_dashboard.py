"""omobd_embed_dashboard.py -- build src/omobd/dashboard_html.h

Takes dashboard/index.html, injects the engine-profile catalog from
engine-profiles/*/*.profile.json, gzips it (deterministically) and writes it
as a byte array the firmware serves at "/".

Runs automatically as a PlatformIO pre-script for the esp32s3_omobd env, and
can be run by hand:  python3 scripts/omobd_embed_dashboard.py
The generated header is committed so a plain checkout builds without Python
side effects; the script only rewrites it when the content changes.
"""
import glob
import gzip
import io
import json
import os

try:
    Import("env")  # noqa: F821  (PlatformIO/SCons)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(ROOT, "dashboard", "index.html")
OUT = os.path.join(ROOT, "src", "omobd", "dashboard_html.h")
MARK = "/*OMOBD_PROFILES*/[]"


def catalog():
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, "engine-profiles", "*", "*.profile.json"))):
        with open(path) as fh:
            p = json.load(fh)
        out.append({
            "id": p["id"],
            "name": p.get("name"),
            "status": p.get("status"),
            "statusNote": p.get("statusNote"),
            "variants": [{"id": v["id"], "label": v.get("label"), "aspiration": v.get("aspiration")}
                         for v in p.get("variants", [])],
            "capabilities": {k: {"app": c.get("app"), "status": c.get("status")}
                             for k, c in p.get("capabilities", {}).items()},
            "dashboard": p.get("dashboard"),
        })
    return out


def build():
    with open(SRC, encoding="utf-8") as fh:
        html = fh.read()
    if MARK not in html:
        raise SystemExit("omobd_embed_dashboard: profile marker missing from dashboard/index.html")
    html = html.replace(MARK, json.dumps(catalog(), separators=(",", ":")))
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as gz:
        gz.write(html.encode("utf-8"))
    data = buf.getvalue()
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    header = (
        "// GENERATED by scripts/omobd_embed_dashboard.py from dashboard/index.html\n"
        "// and engine-profiles/. Do not edit by hand.\n"
        "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"
        "static const size_t OMOBD_DASHBOARD_HTML_GZ_LEN = %d;\n"
        "static const uint8_t OMOBD_DASHBOARD_HTML_GZ[] PROGMEM = {\n%s\n};\n"
        % (len(data), "\n".join(lines))
    )
    old = None
    if os.path.exists(OUT):
        with open(OUT) as fh:
            old = fh.read()
    if old != header:
        with open(OUT, "w") as fh:
            fh.write(header)
        print("omobd_embed_dashboard: wrote %s (%d bytes gzipped)" % (os.path.relpath(OUT, ROOT), len(data)))


build()
